import { afterEach, describe, expect, it, vi } from 'vitest'
import { ApiError, request } from '../src/api'

afterEach(() => { vi.useRealTimers(); vi.unstubAllGlobals() })
const never = () => new Promise<never>(() => {})
describe('bounded JSON requests', () => {
  it('bounds a read at 15 seconds and removes its timer', async () => {
    vi.useFakeTimers()
    const fetch = vi.fn(never); vi.stubGlobal('fetch', fetch)
    const result = request('/fixture/read').catch(error => error as ApiError)
    await vi.advanceTimersByTimeAsync(14_999)
    expect((fetch.mock.calls[0]?.[1] as RequestInit).signal?.aborted).toBe(false)
    await vi.advanceTimersByTimeAsync(1)
    expect(await result).toMatchObject({ code: 'REQUEST_TIMEOUT', status: 0 })
    expect((fetch.mock.calls[0]?.[1] as RequestInit).signal?.aborted).toBe(true)
    expect(vi.getTimerCount()).toBe(0)
  })
  it('bounds writes at 30 seconds without silently resending', async () => {
    vi.useFakeTimers()
    const fetch = vi.fn(never); vi.stubGlobal('fetch', fetch)
    const result = request('/fixture/write', 'POST', { value: 'fixture' }).catch(error => error as ApiError)
    await vi.advanceTimersByTimeAsync(15_000)
    expect((fetch.mock.calls[0]?.[1] as RequestInit).signal?.aborted).toBe(false)
    await vi.advanceTimersByTimeAsync(15_000)
    expect((await result).uncertain).toBe(true)
    await vi.advanceTimersByTimeAsync(60_000)
    expect(fetch).toHaveBeenCalledTimes(1)
  })
  it.each([true, false])('includes %s response-body reading in the same timeout budget', async ok => {
    vi.useFakeTimers()
    vi.stubGlobal('fetch', vi.fn(async () => ({ ok, status: ok ? 200 : 503, headers: new Headers({ 'X-Trace-Id': 'fixture-trace' }), json: never })))
    const result = request('/fixture/body', 'GET', undefined, undefined, undefined, { timeoutMs: 25 }).catch(error => error as ApiError)
    await vi.advanceTimersByTimeAsync(25)
    expect(await result).toMatchObject({ code: 'REQUEST_TIMEOUT', traceId: 'fixture-trace' })
    expect(vi.getTimerCount()).toBe(0)
  })
  it('distinguishes an explicitly cancelled read from an uncertain write', async () => {
    const fetch = vi.fn(never); vi.stubGlobal('fetch', fetch)
    const controller = new AbortController()
    const read = request('/fixture/read', 'GET', undefined, undefined, undefined, { signal: controller.signal }).catch(error => error as ApiError)
    const write = request('/fixture/write', 'POST', {}, undefined, undefined, { signal: controller.signal }).catch(error => error as ApiError)
    controller.abort()
    expect((await read).cancelled).toBe(true); expect((await read).uncertain).toBe(false)
    expect((await write).cancelled).toBe(false); expect((await write).uncertain).toBe(true)
    expect(fetch).toHaveBeenCalledTimes(2)
  })
  it('does not contact the server for an already-cancelled read', async () => {
    const fetch = vi.fn(); vi.stubGlobal('fetch', fetch)
    const controller = new AbortController(); controller.abort()
    await expect(request('/fixture/read', 'GET', undefined, undefined, undefined, { signal: controller.signal })).rejects.toMatchObject({ code: 'REQUEST_CANCELLED' })
    expect(fetch).not.toHaveBeenCalled()
  })
  it('cleans cancellation listeners after success without aborting the settled request', async () => {
    vi.useFakeTimers()
    const fetch = vi.fn(async () => Response.json({ fixture: true })); vi.stubGlobal('fetch', fetch)
    const controller = new AbortController(), remove = vi.spyOn(controller.signal, 'removeEventListener')
    await expect(request('/fixture/read', 'GET', undefined, undefined, undefined, { signal: controller.signal })).resolves.toEqual({ fixture: true })
    controller.abort()
    expect((fetch.mock.calls[0]?.[1] as RequestInit).signal?.aborted).toBe(false)
    expect(remove).toHaveBeenCalledWith('abort', expect.any(Function)); expect(vi.getTimerCount()).toBe(0)
  })
  it('preserves a rejected status and safe trace without rendering arbitrary problem details', async () => {
    vi.stubGlobal('fetch', vi.fn(async () => Response.json({ code: 'INVALID_STATE', traceId: 'fixture:trace-01', detail: 'do-not-display secret' }, { status: 409 })))
    const error = await request('/fixture/read').catch(error => error as ApiError)
    expect(error.status).toBe(409); expect(error.traceId).toBe('fixture:trace-01')
    expect(error.message).not.toContain('secret'); expect(error.message).not.toContain('管理员')
    expect(new ApiError(400, 'INVALID_REQUEST', '<script>secret</script>').traceId).toBeUndefined()
  })
})
